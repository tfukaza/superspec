import type { ItemReport, ParameterValue } from "../../browser/runtime/authoring.ts";

/**
 * The scene's items as the engine reports them: per item, a slider and a number for every numeric control (their
 * ranges come from the definition), a checkbox or list for the others, the derived values, the parts with their
 * geometry keys (the parts the last edit generated are marked) and what the item names: features, attachments, decals.
 * A slider asks for values while it moves (`dragging`), then once more when it is let go.
 */
export class ItemPanel {
  private signature = "";
  constructor(private readonly host: HTMLElement,
    private readonly change: (item: string, parameter: string, value: ParameterValue, dragging: boolean) => void) {}

  show(items: Record<string, ItemReport>): void {
    const signature = JSON.stringify(Object.entries(items).map(([id, item]) => [id, item.definition,
      item.parameters.map(({ name, type, min, max, unit, choices }) => [name, type, min, max, unit, choices])]));
    if (signature !== this.signature) {
      this.signature = signature;
      this.host.replaceChildren(...Object.entries(items).map(([id, item]) => this.block(id, item)));
    }
    for (const [id, item] of Object.entries(items)) {
      const block = this.host.querySelector<HTMLElement>(`details[data-item="${CSS.escape(id)}"]`);
      if (!block) continue;
      block.querySelector("summary")!.textContent = `${id} · ${item.definition} · ${item.parts.length} part${item.parts.length === 1 ? "" : "s"}`;
      for (const parameter of item.parameters) {
        for (const input of block.querySelectorAll<HTMLInputElement | HTMLSelectElement>(`[data-parameter="${CSS.escape(parameter.name)}"] input, [data-parameter="${CSS.escape(parameter.name)}"] select`)) {
          if (input === document.activeElement) continue;
          if (input instanceof HTMLInputElement && input.type === "checkbox") input.checked = Boolean(parameter.value);
          else input.value = String(parameter.value);
        }
      }
      const list = (name: string, rows: { text: string; data?: Record<string, string> }[]): void => {
        const host = block.querySelector<HTMLElement>(`ul.${name}`)!;
        host.replaceChildren(...rows.map(row => {
          const entry = document.createElement("li");
          entry.textContent = row.text;
          Object.assign(entry.dataset, row.data ?? {});
          return entry;
        }));
      };
      list("item-derived", Object.entries(item.derived).map(([name, value]) => ({ text: `${name} = ${+value.toFixed(4)}`, data: { derived: name } })));
      list("item-parts", item.parts.map(part => ({ text: `${part.id} · key ${part.key.slice(0, 8)} · ${part.meshes.length} mesh${part.meshes.length === 1 ? "" : "es"}${part.rebuilt ? " · generated by the last edit" : ""}`,
        data: { part: part.id, key: part.key, rebuilt: String(part.rebuilt) } })));
      const counts = new Map<string, number>();
      for (const feature of item.features) counts.set(feature.name, (counts.get(feature.name) ?? 0) + 1);
      list("item-named", [
        ...(counts.size ? [{ text: `Features: ${[...counts].map(([name, count]) => `${name} ×${count}`).join(", ")}` }] : []),
        ...(item.attachments.length ? [{ text: `Attachments: ${item.attachments.map(attachment => attachment.name).join(", ")}` }] : []),
        ...item.decals.map(decal => ({ text: `Decal ${decal.id}: ${decal.image} on ${decal.part}/${decal.face}, ${decal.size.join(" × ")} m`, data: { decal: decal.id } })),
        ...item.handles.map(handle => ({ text: `Handle ${handle.id} drags ${handle.parameter}`, data: { handle: handle.id } })),
      ]);
    }
  }

  private block(id: string, item: ItemReport): HTMLElement {
    const block = document.createElement("details");
    block.open = true; block.dataset.item = id;
    block.append(document.createElement("summary"));
    for (const parameter of item.parameters) {
      const row = document.createElement("div"); row.className = "item-control"; row.dataset.parameter = parameter.name;
      const label = document.createElement("span");
      const numeric = parameter.type === "number" || parameter.type === "integer";
      label.textContent = `${parameter.name}${parameter.unit ? ` (${parameter.unit})` : ""}${numeric && parameter.min !== undefined && parameter.max !== undefined ? ` · ${parameter.min} to ${parameter.max}` : ""}`;
      row.append(label);
      if (numeric) {
        const step = String(parameter.type === "integer" ? 1 : 0.01);
        const number = document.createElement("input"); number.type = "number"; number.step = step;
        number.setAttribute("aria-label", `${id} ${parameter.name}`);
        if (parameter.min !== undefined) number.min = String(parameter.min);
        if (parameter.max !== undefined) number.max = String(parameter.max);
        number.addEventListener("change", () => { if (Number.isFinite(number.valueAsNumber)) this.change(id, parameter.name, number.valueAsNumber, false); });
        // A slider needs both ends of a range.
        if (parameter.min !== undefined && parameter.max !== undefined) {
          const slider = document.createElement("input"); slider.type = "range"; slider.step = step;
          slider.min = String(parameter.min); slider.max = String(parameter.max);
          slider.setAttribute("aria-label", `${id} ${parameter.name} slider`);
          slider.addEventListener("input", () => { number.value = slider.value; this.change(id, parameter.name, slider.valueAsNumber, true); });
          slider.addEventListener("change", () => this.change(id, parameter.name, slider.valueAsNumber, false));
          row.append(slider);
        } else row.append(document.createElement("span"));
        row.append(number);
      } else if (parameter.type === "boolean") {
        const box = document.createElement("input"); box.type = "checkbox"; box.setAttribute("aria-label", `${id} ${parameter.name}`);
        box.addEventListener("change", () => this.change(id, parameter.name, box.checked, false));
        row.append(box);
      } else if (parameter.type === "choice") {
        const select = document.createElement("select"); select.setAttribute("aria-label", `${id} ${parameter.name}`);
        for (const choice of parameter.choices ?? []) select.add(new Option(choice, choice));
        select.addEventListener("change", () => this.change(id, parameter.name, select.value, false));
        row.append(select);
      } else {
        const text = document.createElement("input"); text.type = "text"; text.setAttribute("aria-label", `${id} ${parameter.name}`);
        text.addEventListener("change", () => this.change(id, parameter.name, text.value, false));
        row.append(text);
      }
      block.append(row);
    }
    for (const name of ["item-derived", "item-parts", "item-named"]) {
      const list = document.createElement("ul"); list.className = name;
      block.append(list);
    }
    return block;
  }
}
