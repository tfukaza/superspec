//! Source preparation shared by assembly and source-only callers.
use superspec_aml::{
    architecture::{Document, parse_with_registry},
    diagnostic::Diagnostic,
    extensions::Registry,
};

/// Typed authored source with registered source checks and common material declarations.
/// Architectural references, physical geometry and navigation are not certified here.
#[derive(Debug)]
pub struct PreparedDocument {
    pub(crate) document: Document,
}

impl PreparedDocument {
    pub fn document(&self) -> &Document {
        &self.document
    }
}

/// Source checks see authored declarations, before the common catalog fills reserved references.
/// No assets are read and no geometry is generated by this boundary.
pub fn prepare(source: &str, registry: &Registry) -> Result<PreparedDocument, Diagnostic> {
    let mut document = parse_with_registry(source, registry)?;
    superspec_aml::material_catalog::register(&mut document)?;
    Ok(PreparedDocument { document })
}
